"""Bakes the Barlow glyphs Vitals draws its text with into packages/vitals/tool/font.js.

    python scripts/bake_font.py

Each style is one Barlow weight at one pixel size. Per glyph: advance, x/y offset of its
bitmap from the pen (y from the baseline, up negative), size, and the 8-bit coverage as
base64. font.js works under Node (module.exports) and in a browser (window.VITALS_FONT),
so packages/vitals/design/widget_preview.html draws with the exact same glyphs as the car.
Barlow: SIL Open Font License 1.1 (shared/fonts/OFL-Barlow.txt).
"""
import base64
import json
import os

from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONTS = os.path.join(ROOT, "shared", "fonts")
OUT = os.path.join(ROOT, "packages", "vitals", "tool", "font.js")
APP_OUT = os.path.join(ROOT, "packages", "vitals", "app", "src", "ui_font.js")

STYLES = {
    # name: (file, px)
    "value": ("Barlow-Light.ttf", 46),     # the bars' readouts
    "unit": ("Barlow-Regular.ttf", 23),    # degree units
    "label": ("Barlow-Medium.ttf", 19),    # WATER, ENGINE OIL, TYRES (spaced capitals)
    "tyre": ("Barlow-Regular.ttf", 54),    # tyre temperatures
    "tyreP": ("Barlow-Regular.ttf", 34),   # tyre pressures
    "tyreUnit": ("Barlow-Regular.ttf", 24),  # their units
}
CHARS = "".join(chr(c) for c in range(32, 127)) + "\N{DEGREE SIGN}\N{EN DASH}\N{MIDDLE DOT}"
NUMS = "0123456789.,-+ %\N{DEGREE SIGN}\N{EN DASH}CFabrkPpsi"

# the Vitals app's own screen (app/src/ui.js, drawn by the head unit's renderer at 2880 px wide)
APP_STYLES = {
    # name: (file, px, characters)
    "title": ("Barlow-SemiBold.ttf", 54, CHARS),
    "head": ("Barlow-Medium.ttf", 28, CHARS),
    "body": ("Barlow-Regular.ttf", 34, CHARS),
    "strong": ("Barlow-Medium.ttf", 38, CHARS),
    "small": ("Barlow-Regular.ttf", 26, CHARS),
    "big": ("Barlow-Light.ttf", 96, NUMS),
    "mid": ("Barlow-Regular.ttf", 58, NUMS),
}


def bake(file, px, chars=CHARS):
    font = ImageFont.truetype(os.path.join(FONTS, file), px)
    ascent, descent = font.getmetrics()
    glyphs = {}
    for ch in chars:
        adv = font.getlength(ch)
        l, t, r, b = font.getbbox(ch, anchor="ls")
        w, h = max(0, r - l), max(0, b - t)
        data = ""
        if w and h:
            img = Image.new("L", (w, h), 0)
            ImageDraw.Draw(img).text((-l, -t), ch, font=font, fill=255, anchor="ls")
            data = base64.b64encode(img.tobytes()).decode("ascii")
        glyphs[ch] = [round(adv, 2), l, t, w, h, data]
    return {"px": px, "ascent": ascent, "descent": descent, "glyphs": glyphs}


def main():
    font = {name: bake(*spec) for name, spec in STYLES.items()}
    body = json.dumps(font, separators=(",", ":"), ensure_ascii=True)
    with open(OUT, "w", encoding="ascii", newline="\n") as f:
        f.write("/* generated by scripts/bake_font.py from Barlow (SIL OFL 1.1, fonts/OFL-Barlow.txt); do not edit */\n")
        f.write("(function (root) {\n    var FONT = " + body + ";\n")
        f.write("    if (typeof module !== 'undefined' && module.exports) module.exports = FONT;\n")
        f.write("    else root.VITALS_FONT = FONT;\n})(this);\n")
    print("wrote", OUT, os.path.getsize(OUT), "bytes")
    app = {name: bake(*spec) for name, spec in APP_STYLES.items()}
    with open(APP_OUT, "w", encoding="ascii", newline="\n") as f:
        f.write("'use strict';\n/* generated by scripts/bake_font.py from Barlow (SIL OFL 1.1); do not edit.\n")
        f.write(" * The Vitals app screen's glyphs: style -> { px, ascent, descent, glyphs: { char: [advance, x, y, w, h, base64] } } */\n")
        f.write("module.exports = " + json.dumps(app, separators=(",", ":"), ensure_ascii=True) + ";\n")
    print("wrote", APP_OUT, os.path.getsize(APP_OUT), "bytes")


if __name__ == "__main__":
    main()
